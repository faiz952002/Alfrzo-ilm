// Alfrzo Ilm server. Zero npm dependencies (Node 20+).
//   * serves the static app and injects PUBLIC config from environment variables
//   * security headers + rate limiting
//   * payment order creation / verification / webhook (the only place secrets are used)
//   * per-question SEO tags and sitemap
import http from 'node:http';
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadConfig, publicConfig } from './config.js';
import { RateLimiter, securityHeaders, clientIp } from './security.js';
import { supabaseClient, razorpayClient } from './upstream.js';
import { paymentsApi } from './payments.js';
import { seo } from './seo.js';

const MIME = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.ico': 'image/x-icon', '.txt': 'text/plain; charset=utf-8', '.xml': 'application/xml; charset=utf-8',
};
const HOST_RE = /^[a-z0-9.-]+(:\d{1,5})?$/i;

export function createServer(cfg = loadConfig(), log = console) {
  const limiter = new RateLimiter();
  const sb = (cfg.supabaseReady || cfg.paymentsReady) ? supabaseClient(cfg) : null;
  const pay = cfg.paymentsReady ? paymentsApi(cfg, { sb, rzp: razorpayClient(cfg), limiter, log }) : null;
  const seoApi = seo(cfg, sb);
  const publicJs = `// Generated by the server from environment variables. Contains only public values.\nwindow.ASKDEEN = ${JSON.stringify(publicConfig(cfg))};\n`;

  const origin = req => {
    if (cfg.siteUrl) return cfg.siteUrl;
    const proto = cfg.trustProxy ? String(req.headers['x-forwarded-proto'] || 'http').split(',')[0] : (req.socket.encrypted ? 'https' : 'http');
    const host = String(req.headers.host || '');
    return `${proto === 'https' ? 'https' : 'http'}://${HOST_RE.test(host) ? host : 'localhost'}`;
  };
  const text = (res, status, body, type, extra = {}) => { res.writeHead(status, { 'Content-Type': type, ...extra }); res.end(body); };
  const json = (res, status, obj) => text(res, status, JSON.stringify(obj), 'application/json; charset=utf-8', { 'Cache-Control': 'no-store' });

  let indexHtml = null;
  const getIndex = async () => indexHtml ??= await fs.readFile(path.join(cfg.publicDir, 'index.html'), 'utf8');

  async function serveStatic(req, res, pathname) {
    let rel;
    try { rel = decodeURIComponent(pathname); } catch { return text(res, 400, 'Bad request', 'text/plain'); }
    if (rel.includes('\0')) return text(res, 400, 'Bad request', 'text/plain');
    const file = path.resolve(cfg.publicDir, '.' + path.posix.normalize('/' + rel));
    const inside = file === cfg.publicDir || file.startsWith(cfg.publicDir + path.sep);
    const hidden = file.split(path.sep).some(p => p.startsWith('.'));
    const ext = path.extname(file).toLowerCase();

    if (inside && !hidden && ext) {
      try {
        const st = await fs.stat(file);
        if (st.isFile()) {
          const body = req.method === 'HEAD' ? null : await fs.readFile(file);
          const cache = ext === '.html' || file.endsWith('sw.js') ? 'no-cache' : (/\/(js|css)\//.test(pathname) ? 'public, max-age=300' : 'public, max-age=86400');
          res.writeHead(200, { 'Content-Type': MIME[ext] || 'application/octet-stream', 'Cache-Control': cache, 'Content-Length': st.size });
          return res.end(body);
        }
      } catch { /* fall through to 404 */ }
      return text(res, 404, 'Not found', 'text/plain; charset=utf-8');
    }
    if (ext) return text(res, 404, 'Not found', 'text/plain; charset=utf-8');

    // Single-page app route: send index.html (with per-question SEO tags for /q/:id)
    let html = await getIndex();
    const m = /^\/q\/([0-9a-f-]{36})\/?$/i.exec(pathname);
    if (m) html = await seoApi.injectQuestion(html, m[1], origin(req));
    text(res, 200, req.method === 'HEAD' ? '' : html, MIME['.html'], { 'Cache-Control': 'no-cache' });
  }

  async function handler(req, res) {
    const url = new URL(req.url, 'http://x'); const p = url.pathname;
    for (const [k, v] of Object.entries(securityHeaders(cfg, req))) res.setHeader(k, v);
    const ip = clientIp(req, cfg.trustProxy);

    if (p.startsWith('/api/')) {
      if (!limiter.take('ip:' + ip, 120, 60_000)) return json(res, 429, { error: 'Too many requests' });
      if (p === '/api/health') return json(res, 200, { ok: true, supabase: cfg.supabaseReady, payments: cfg.paymentsReady });
      if (p.startsWith('/api/payments/')) {
        if (!pay) return json(res, 503, { error: 'Payments are not configured' });
        if (req.method !== 'POST') return json(res, 405, { error: 'Use POST' });
        if (p === '/api/payments/create-order') return pay.createOrder(req, res);
        if (p === '/api/payments/consultation-order') return pay.consultationOrder(req, res);
        if (p === '/api/payments/verify') return pay.verify(req, res);
        if (p === '/api/payments/webhook') return pay.webhook(req, res);
      }
      return json(res, 404, { error: 'Not found' });
    }

    if (req.method !== 'GET' && req.method !== 'HEAD') return text(res, 405, 'Method not allowed', 'text/plain', { Allow: 'GET, HEAD' });

    if (p === '/js/config.js' || p === '/config.js') return text(res, 200, publicJs, MIME['.js'], { 'Cache-Control': 'no-store' });
    if (p === '/sitemap.xml') return text(res, 200, await seoApi.sitemap(origin(req)), MIME['.xml'], { 'Cache-Control': 'public, max-age=600' });
    if (p === '/robots.txt') {
      let t; try { t = await fs.readFile(path.join(cfg.publicDir, 'robots.txt'), 'utf8'); } catch { t = 'User-agent: *\nAllow: /\n'; }
      return text(res, 200, t.replace(/^Sitemap:.*$/m, '').trimEnd() + `\nSitemap: ${origin(req)}/sitemap.xml\n`, MIME['.txt'], { 'Cache-Control': 'public, max-age=3600' });
    }
    return serveStatic(req, res, p);
  }

  const server = http.createServer((req, res) => {
    handler(req, res).catch(e => { log.error('unhandled:', e?.message); if (!res.headersSent) json(res, 500, { error: 'Server error' }); else res.end(); });
  });
  server.headersTimeout = 15_000; server.requestTimeout = 30_000; server.keepAliveTimeout = 5_000;
  return server;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const cfg = loadConfig();
  createServer(cfg).listen(cfg.port, () => {
    const on = b => (b ? 'on' : 'OFF');
    console.log(`Alfrzo Ilm listening on :${cfg.port}`);
    console.log(`  Supabase configured : ${on(cfg.supabaseReady)}${cfg.supabaseReady ? '' : '  (set SUPABASE_URL and SUPABASE_ANON_KEY, the app shows a setup screen until then)'}`);
    console.log(`  Payments (Razorpay) : ${on(cfg.paymentsReady)}   webhook: ${on(cfg.webhookReady)}`);
    for (const p of cfg.problems) console.warn('  WARNING: ' + p);
  });
}
